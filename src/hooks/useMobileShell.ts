import { useMediaQuery } from './useMediaQuery';
import { detectPlatform } from '../services/nativeBridge';

/**
 * Показывать ли телефонный интерфейс вместо настольного.
 *
 * До этой развилки «мобильным» считалось узкое окно, и один и тот же экран
 * подстраивался под оба случая полусотней ветвлений `isNarrow` внутри общих
 * компонентов. Каждая правка ради телефона рисковала задеть ПК, а каждая
 * телефонная находка упиралась в чужую разметку — потолок был достигнут.
 * Отдельное дерево снимает и то, и другое: настольные компоненты перестают
 * знать про телефон вовсе.
 *
 * Признаков два, и оба нужны:
 *
 * - `detectPlatform() === 'mobile'` — настоящий телефон. Это гарантия: в APK
 *   телефонный вид обязан быть при любой ширине, включая планшет в альбомной
 *   ориентации, где 768 px давно позади.
 * - ширина ≤ 768 px — рабочая петля. Круг правок по вёрстке идёт в браузере на
 *   360×800 с засеянной базой, это секунды против минут на сборку APK. Без
 *   ширины в условии смотреть телефонный экран было бы негде.
 *
 * Побочное следствие второго признака: узкое окно Electron на ПК тоже получит
 * телефонный вид. Так было и раньше — вся мобильная вёрстка и до этого шла по
 * ширине, — но теперь это осознанный выбор, а не совпадение. Узкому окну
 * телефонная раскладка идёт больше, чем сжатая настольная.
 */
export function useMobileShell(): boolean {
  const isNarrow = useMediaQuery('(max-width: 768px)');
  // Платформа за время работы приложения не меняется, поэтому хук ей не нужен;
  // ширина меняется, и её обязан слушать `useMediaQuery`.
  return detectPlatform() === 'mobile' || isNarrow;
}
