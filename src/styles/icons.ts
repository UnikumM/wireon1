/**
 * Единственная шкала размеров иконок.
 *
 * Зачем она нужна: в lucide `strokeWidth` задан в единицах viewBox (24), то
 * есть реальная толщина линии на экране — `strokeWidth × size / 24`. Пока
 * размеры расползаются (в приложении их было 21, от 10 до 64 px), штрих гуляет
 * от 0.83 px до 5.33 px: мелкие иконки выглядят бледными и размытыми, крупные —
 * нарисованными маркером. Толщину выравнивает рампа в `global.css`, а этот
 * файл убирает вторую половину проблемы — сами размеры.
 *
 * CSS-переменной здесь не обойтись: `size` у lucide — числовой проп React.
 * Парные размеры кнопок живут в `theme.css` как `--control-*`.
 */
export const ICON = {
  /** 12 — бейджи, инлайн-мета, счётчики. Пара к `--control-xs`. */
  xs: 12,
  /** 14 — плотные строки, кнопки окна, мини-плеер. Пара к `--control-sm`. */
  sm: 14,
  /** 16 — размер по умолчанию: тулбары, меню, строки списка. Пара к `--control-md`. */
  md: 16,
  /** 20 — навигация, prev/next, иконки заголовков секций. Пара к `--control-lg`. */
  lg: 20,
  /** 24 — главный play/pause в баре. Пара к `--control-xl`. */
  xl: 24,
  /** 28 — главный play/pause во весь экран. Пара к `--control-2xl`. */
  '2xl': 28,
  /** 32 — глиф пустого состояния. */
  display: 32,
  /** 48 — крупная заглушка вместо обложки (фуллскрин, мини-квадрат). */
  hero: 48
} as const;

export type IconSize = (typeof ICON)[keyof typeof ICON];

export default ICON;
