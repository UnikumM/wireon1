/**
 * Подписи-заглушки для треков без метаданных.
 *
 * Раньше «Unknown Artist» было раскидано по парсерам и одновременно служило
 * маркером: агрегатор и движок рекомендаций сравнивали строку с этим значением,
 * чтобы не искать похожее по несуществующему имени. Перевод строк в одном месте
 * ломал бы такие проверки в другом, поэтому и подпись, и проверка живут здесь.
 */

/** Что показываем вместо исполнителя, если источник его не отдал. */
export const UNKNOWN_ARTIST = 'Неизвестный исполнитель';

/** Что показываем вместо названия трека, если источник его не отдал. */
export const UNKNOWN_TITLE = 'Без названия';

/** Название плейлиста, если пользователь оставил поле пустым. */
export const UNTITLED_PLAYLIST = 'Плейлист без названия';

/**
 * Имя исполнителя — заглушка, а не реальное имя? По такому нельзя искать похожее
 * и нельзя строить радио, поэтому проверка нужна многим. Английские варианты
 * оставлены: они приходят из старых сохранённых треков и из ответов источников.
 */
const PLACEHOLDER_ARTISTS = new Set([
  UNKNOWN_ARTIST.toLowerCase(),
  'unknown artist',
  'unknown',
  'various artists',
  'неизвестен',
  'неизвестный'
]);

export function isPlaceholderArtist(artist: string | null | undefined): boolean {
  if (!artist) return true;
  return PLACEHOLDER_ARTISTS.has(artist.trim().toLowerCase());
}
