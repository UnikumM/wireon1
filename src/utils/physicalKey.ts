/**
 * Какая клавиша нажата — независимо от раскладки.
 *
 * `event.key` отдаёт то, что клавиша печатает: на русской раскладке у `K` это
 * «л», у `M` — «ь». Сочетания, сверявшие `event.key` с латинской буквой, на
 * кириллице молчали целиком — отсюда «Ctrl+K не работает вообще» и «половина
 * биндов не работает на русской раскладке».
 *
 * `event.code` называет саму клавишу (`KeyK`), что бы на ней ни было нарисовано.
 * Но и одним `code` обойтись нельзя: на Dvorak и AZERTY буквы стоят на других
 * местах, и там человек жмёт клавишу с нужной буквой, а не ту, где она была бы
 * на QWERTY. Поэтому порядок такой:
 *
 * 1. клавиша печатает латинскую букву — верим ей (любая латинская раскладка);
 * 2. иначе берём место клавиши из `code` (кириллица, греческая, иврит, а ещё
 *    macOS, где Alt+буква печатает значок);
 * 3. `code` пуст (старые WebView, синтетические события) — переводим русскую
 *    или украинскую букву по её месту на ЙЦУКЕН.
 */

/** Кириллица на буквенных клавишах: что напечатано → чем была бы клавиша на QWERTY. */
const CYRILLIC_TO_LATIN: Readonly<Record<string, string>> = {
  й: 'q', ц: 'w', у: 'e', к: 'r', е: 't', н: 'y', г: 'u', ш: 'i', щ: 'o', з: 'p',
  ф: 'a', ы: 's', в: 'd', а: 'f', п: 'g', р: 'h', о: 'j', л: 'k', д: 'l',
  я: 'z', ч: 'x', с: 'c', м: 'v', и: 'b', т: 'n', ь: 'm',
  // Украинская раскладка: те же места, другие буквы.
  і: 's'
};

type KeyLike = Pick<KeyboardEvent, 'key' | 'code'>;

/**
 * Латинская буква нажатой клавиши в нижнем регистре или `null`, если клавиша
 * не буквенная. `Ctrl+Л` и `Ctrl+K` здесь одно и то же: `'k'`.
 */
export function shortcutLetter(event: KeyLike): string | null {
  const key = event.key || '';
  if (/^[a-zA-Z]$/.test(key)) return key.toLowerCase();

  const byCode = /^Key([A-Z])$/.exec(event.code || '');
  if (byCode) return byCode[1].toLowerCase();

  if (!event.code && key.length === 1) return CYRILLIC_TO_LATIN[key.toLowerCase()] ?? null;
  return null;
}

/**
 * Нажата ли клавиша `/` — та, что справа от точки на QWERTY.
 *
 * На русской раскладке она печатает точку, а сам знак `/` уезжает на
 * Shift+`\`. Принимаем и клавишу по месту, и знак, чем бы он ни был набран.
 */
export function isSlashKey(event: Pick<KeyboardEvent, 'key' | 'code' | 'shiftKey'>): boolean {
  if (event.key === '/') return true;
  // Буква на этом месте (Dvorak: `z`) — это буква, а не «клавиша поиска».
  if (/^[a-zA-Z]$/.test(event.key || '')) return false;
  return event.code === 'Slash' && !event.shiftKey;
}
