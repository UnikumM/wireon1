const SEMVER = /^(\d+)\.(\d+)\.(\d+)$/;

/**
 * Сравнивает `x.y.z`: отрицательное — `a` старше, положительное — новее.
 *
 * Непонятная строка считается самой старой: так неизвестная версия в хранилище
 * приводит к показу списка, а не к молчанию, — из двух ошибок эта безобиднее.
 */
export function compareVersions(a: string, b: string): number {
  const left = a.match(SEMVER);
  const right = b.match(SEMVER);
  if (!left && !right) return 0;
  if (!left) return -1;
  if (!right) return 1;

  for (let i = 1; i <= 3; i++) {
    const diff = Number(left[i]) - Number(right[i]);
    if (diff !== 0) return diff;
  }
  return 0;
}

/**
 * Записи, которые человек ещё не видел: новее `previousVersion` и не новее
 * текущей сборки.
 *
 * Верхняя граница здесь не для красоты: заготовка следующего выпуска лежит в
 * списке заранее, и без неё сборка обещала бы то, чего в ней ещё нет.
 * `previousVersion === null` — истории нет, показывать нечего.
 */
export function entriesSince(
  previousVersion: string | null,
  currentVersion: string,
  entries: ReadonlyArray<ChangelogEntry> = CHANGELOG
): ChangelogEntry[] {
  if (!previousVersion) return [];
  return entries
    .filter(
      (entry) =>
        compareVersions(entry.version, previousVersion) > 0 &&
        compareVersions(entry.version, currentVersion) <= 0
    )
    .sort((a, b) => compareVersions(b.version, a.version));
}

/** Запись ровно про эту версию — для повторного показа из настроек. */
export function entryFor(
  version: string,
  entries: ReadonlyArray<ChangelogEntry> = CHANGELOG
): ChangelogEntry | null {
  return entries.find((entry) => compareVersions(entry.version, version) === 0) ?? null;
}

/** «22 августа 2026» — как это читают вслух. */
export function formatEntryDate(date: string): string {
  const parsed = new Date(`${date}T00:00:00`);
  if (Number.isNaN(parsed.getTime())) return date;
  try {
    return parsed.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' });
  } catch {
    return date;
  }
}

