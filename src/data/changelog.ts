/**
 * Что менялось в приложении — списком, для экрана «Что нового».
 *
 * Почему это файл в коде, а не текст релиза с GitHub: заметки к релизу рисует
 * **старая установленная** версия, та, что обновление нашла. Значит любой новый
 * вид этих заметок впервые сработал бы только через выпуск. Список, зашитый в
 * сборку, показывает сама новая версия — сразу и без сети, в том числе если
 * человек поставил обновление вручную или сидит в офлайне.
 *
 * Порядок — от новой версии к старой. Записи для ещё не выпущенной версии здесь
 * лежать могут: `entriesSince` не отдаёт то, что новее текущей сборки.
 */

export type ChangelogKind = 'feature' | 'change' | 'fix';

export interface ChangelogItem {
  kind: ChangelogKind;
  /** Что изменилось — с точки зрения слушателя, а не кода. */
  title: string;
  /** Подробность на одну фразу. Не обязательна. */
  detail?: string;
}

export interface ChangelogEntry {
  /** Строго `x.y.z`: сравнение числовое, суффиксы не разбираются. */
  version: string;
  /** Дата выпуска, `ГГГГ-ММ-ДД`. */
  date: string;
  /** Одна фраза про весь выпуск — заголовок экрана. */
  headline: string;
  items: ChangelogItem[];
}

