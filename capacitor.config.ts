import type { CapacitorConfig } from '@capacitor/cli';

/**
 * Настройки обёртки Android.
 *
 * `webDir` тот же `dist`, что собирает Vite для Electron: приложение одно, и
 * расходиться этим двум сборкам незачем — вся разница между ними живёт в
 * `src/services/nativeBridge.ts`, а не в двух копиях интерфейса.
 *
 * `androidScheme: 'https'` — не украшение. WebView отдаёт страницу с
 * `https://localhost`, и только на защищённом источнике работают Web Audio с
 * автозапуском, IndexedDB в третьих лицах и `navigator.mediaSession`. На
 * `http://localhost` Chrome часть из этого отключает, и выглядит это как
 * «звук не играет на телефоне» без единой ошибки в журнале.
 */
const config: CapacitorConfig = {
  appId: 'pro.wireon.music',
  appName: 'Wireon',
  webDir: 'dist',
  android: {
    // Разметка приложения тёмная; светлый фон WebView успевает мигнуть белым
    // на запуске, и это первое, что видит человек.
    backgroundColor: '#0b0d12'
  },
  server: {
    androidScheme: 'https'
  },
  plugins: {
    /*
     * Запросы уходят через нативный слой, а не через движок страницы.
     *
     * Без этого на телефоне не работали ни поиск, ни SoundCloud, и по двум
     * разным причинам сразу:
     *
     * - страница живёт на `https://localhost`, а наш сервер отвечает по `http`.
     *   Это смешанное содержимое, и WebView режет его раньше, чем дело дойдёт
     *   до CORS, — то есть `network_security_config` тут не помогает вовсе, он
     *   про другой уровень;
     * - у `api-v2.soundcloud.com` нет заголовков CORS, и предзапрос с чужого
     *   источника он не переживает. Именно поэтому SoundCloud «не находит
     *   ничего»: до него не доходит ни один запрос.
     *
     * Нативный слой не знает ни про источник страницы, ни про предзапросы, и
     * обе беды исчезают вместе. Плата — ответы приходят разобранными, поэтому
     * скачивание в офлайн на телефоне надо будет проверять отдельно.
     */
    CapacitorHttp: {
      enabled: true
    }
  }
};

export default config;
